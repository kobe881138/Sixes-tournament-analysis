def tooltip(label: str) -> str:
    english, chinese, formula = KPI_EXPLANATIONS[label]
    return f"{english}\n\n{chinese}\n\n{formula}"


def overview_kpis(kpis: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    """Five specified coach-facing metrics, as team rows. Percent KPI values in 0..100."""
    rows = []
    for team in teams:
        r = kpis.loc[kpis["Team"] == team]
        if r.empty:
            continue
        s = r.iloc[0]
        row = {"Team": team, "Possessions": int(s["Possessions"])}
        for label, col in KPI_FIELDS[1:]:
            row[label] = float(s[col]) * 100
        rows.append(row)
    return pd.DataFrame(rows)


def possession_types(df: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    grouped = df.groupby(["Team", "Possession_Type"], observed=True).size().to_dict()
    totals = df.groupby("Team").size().to_dict()
    rows = []
    for team in teams:
        for ptype in TYPES:
            n = int(grouped.get((team, ptype), 0))
            rows.append({"Team": team, "Possession_Type": ptype, "Count": n,
                         "Share_pct": n / totals[team] * 100 if totals.get(team, 0) else 0.0})
    return pd.DataFrame(rows)


def efficiency_by_type(df: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    rows = []
    for team in teams:
        for ptype in TYPES[:2]:
            group = df.loc[(df["Team"] == team) & (df["Possession_Type"] == ptype)]
            n = len(group)
            goals = int(group["Goal"].sum())
            rows.append({"Team": team, "Possession_Type": ptype,
                         "Possessions": n, "Goals": goals,
                         "Efficiency_pct": goals / n * 100 if n else float("nan"),
                         "Ratio": f"{goals}/{n}" if n else "0/0"})
    return pd.DataFrame(rows)


def end_reasons(df: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    counts = df.groupby(["Team", "End_Reason"], observed=True).size().to_dict()
    totals = df.groupby("Team").size().to_dict()
    rows = []
    for team in teams:
        for reason in END_REASONS:
            count = int(counts.get((team, reason), 0))
            rows.append({"Team": team, "End_Reason": reason, "Count": count,
                         "Share_pct": (count / totals[team] * 100) if totals.get(team, 0) else 0.0})
    return pd.DataFrame(rows)


def infraction_by_team(events: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    if events.empty:
        return pd.DataFrame(columns=["Team", "Infraction_Type", "Count"])
    counts = (events.groupby(["Infraction_Team", "Infraction_Type"], dropna=False)
              .size().reset_index(name="Count"))
    counts = counts.rename(columns={"Infraction_Team": "Team"})
    return counts[counts["Team"].isin(teams)].sort_values(["Team", "Count", "Infraction_Type"], ascending=[True, False, True])


def infraction_changes(events: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    counts = (events.groupby(["Infraction_Team", "Possession_Change"])
              .size().to_dict()) if not events.empty else {}
    rows = []
    for team in teams:
        yes = int(counts.get((team, "Yes"), 0))
        no = int(counts.get((team, "No"), 0))
        n = yes + no
        rows.append({"Team": team, "Yes": yes, "No": no, "Total": n,
                     "Yes_pct": yes / n * 100 if n else float("nan"),
                     "No_pct": no / n * 100 if n else float("nan")})
    return pd.DataFrame(rows)


def computed_final_score(df: pd.DataFrame, home: str, away: str) -> tuple[int,int]:
    """Before-score for last observed possession plus its credited Goal count."""
    last = df.iloc[-1]
    h, a = int(last["Score_Home_Before"]), int(last["Score_Away_Before"])
    if last["Team"] == home:
        h += int(last["Goal"])
    elif last["Team"] == away:
        a += int(last["Goal"])
    return h, a


def score_consistent(df: pd.DataFrame, meta, score_audit: pd.DataFrame) -> bool:
    calculated = computed_final_score(df, meta.team_home, meta.team_away)
    official = (meta.official_final_score_home, meta.official_final_score_away)
    if calculated != official:
        return False
    if not score_audit.empty and ((~score_audit["Matches"].astype(bool)) & (~score_audit["Resynced"].astype(bool))).any():
        return False
    return True


def tempo_medians(times: pd.DataFrame, value_col: str, teams: list[str]) -> pd.DataFrame:
    """Observed median/mean/n for Transition and Settled only, for coach bar charts.

    Excludes Other and missing observations only from the requested metric.
    Preserves missing-type groups as absent, never creates zero-time bars.
    """
    allowed_columns = {"Team", "Possession_Type", value_col}
    absent = allowed_columns.difference(times.columns)
    if absent:
        raise ValueError(f"Missing columns for tempo chart: {sorted(absent)}")
    selected = times.loc[
        times["Team"].isin(teams)
        & times["Possession_Type"].isin(TYPES[:2])
        & times[value_col].notna(),
        ["Team", "Possession_Type", value_col]
    ].copy()
    selected[value_col] = pd.to_numeric(selected[value_col], errors="coerce")
    selected = selected.loc[selected[value_col].notna() & (selected[value_col] >= 0)]
    cols = ["Team", "Possession_Type", "Median_s", "Mean_s", "Valid_n",
            "Possession_Type_Label", "Bar_Label"]
    if selected.empty:
        return pd.DataFrame(columns=cols)
    agg = (
        selected.groupby(["Team", "Possession_Type"], observed=True)[value_col]
        .agg(Median_s="median", Mean_s="mean", Valid_n="size")
        .reset_index()
    )
    agg["Possession_Type_Label"] = agg["Possession_Type"].replace(
        {"Settled_Offense": "Settled Offense"}
    )
    agg["Bar_Label"] = agg.apply(
        lambda row: f"{row['Median_s']:.1f}s  ·  n={row['Valid_n']}", axis=1
    )
    return agg[cols]


def tempo_summary_table(time_by_team: pd.DataFrame, metric: str, teams: list[str]) -> pd.DataFrame:
    """Four-column, team-ordered coach summary. Rows represent *possessions*.

    The first-shot n counts only possessions with an observable shot timestamp;
    missing/no-shot possessions are not silently coded as zero seconds.
    """
    fields = {
        "Possession Duration": (
            "Duration_Valid_n", "Mean_Possession_Duration_s", "Median_Possession_Duration_s"
        ),
        "Time to First Shot": (
            "First_Shot_Valid_n", "Mean_Time_to_First_Shot_s", "Median_Time_to_First_Shot_s"
        ),
    }
    if metric not in fields:
        raise ValueError(f"Unsupported tempo summary metric: {metric}")
    n, avg, median = fields[metric]
    required = ["Team", n, avg, median]
    absent = set(required).difference(time_by_team.columns)
    if absent:
        raise ValueError(f"Missing time-summary columns: {sorted(absent)}")
    table = time_by_team[required].copy()
    table = table.loc[table["Team"].isin(teams)]
    table["Team"] = pd.Categorical(table["Team"], categories=teams, ordered=True)
    table = table.sort_values("Team").reset_index(drop=True)
    table["Team"] = table["Team"].astype(str)
    table[n] = pd.to_numeric(table[n], errors="raise").astype(int)
    table[avg] = pd.to_numeric(table[avg], errors="coerce").round(1)
    table[median] = pd.to_numeric(table[median], errors="coerce").round(1)
    return table.rename(columns={
        n: "Valid Possessions (n)", avg: "Mean (s)", median: "Median (s)",
    })
